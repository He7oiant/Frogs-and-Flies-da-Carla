class Obj {
    constructor(x, y, width, height, color) {
        this.x = x;
        this.y = y;
        this.width = width;
        this.height = height;
        this.color = color;
    }
}
class Player{
    constructor(x,y, speed, vspeed, height, dir, scale, color)
    {
        this.x = x;
        this.y = y;
        this.speed = speed;
        this.vspeed = vspeed;
        this.height = height;
        this.dir = 1;
        this.scale = scale;
        this.sapoandando = false;
        this.gravity= 0.1;
        this.sapopula = false;
        this.color = color;
    }
}

function delay(ms) {
    return new Promise(resolve => setTimeout(resolve, ms));
}

